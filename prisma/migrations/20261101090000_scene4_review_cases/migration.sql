-- A RESOLVED exception is final historical record: it cannot be edited or "un-resolved".
-- If the condition returns, detection creates a NEW exception. Identity columns never change.
CREATE FUNCTION exception_guard_update() RETURNS trigger AS $$
BEGIN
  IF OLD."status" = 'Resolved' THEN
    RAISE EXCEPTION 'A resolved exception is a historical record and cannot be changed. A returning condition creates a new exception';
  END IF;
  IF NEW."customer_id" IS DISTINCT FROM OLD."customer_id"
     OR NEW."exception_type" IS DISTINCT FROM OLD."exception_type"
     OR NEW."source_entity_type" IS DISTINCT FROM OLD."source_entity_type"
     OR NEW."source_entity_id" IS DISTINCT FROM OLD."source_entity_id"
     OR NEW."dedupe_key" IS DISTINCT FROM OLD."dedupe_key"
     OR NEW."detected_at" IS DISTINCT FROM OLD."detected_at"
     OR NEW."exception_code" IS DISTINCT FROM OLD."exception_code" THEN
    RAISE EXCEPTION 'An exception''s identity (customer, type, source, detection date) cannot be changed';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "Exception_guard" BEFORE UPDATE ON "Exception" FOR EACH ROW EXECUTE FUNCTION exception_guard_update();

-- A case never changes customer, code or creation date.
CREATE FUNCTION review_case_guard_update() RETURNS trigger AS $$
BEGIN
  IF NEW."customer_id" IS DISTINCT FROM OLD."customer_id"
     OR NEW."case_code" IS DISTINCT FROM OLD."case_code"
     OR NEW."created_at" IS DISTINCT FROM OLD."created_at" THEN
    RAISE EXCEPTION 'A review case cannot be moved to another customer or change its code';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "ReviewCase_guard" BEFORE UPDATE ON "ReviewCase" FOR EACH ROW EXECUTE FUNCTION review_case_guard_update();

-- Schedule rows are history once they are no longer the current (Scheduled) row.
CREATE FUNCTION review_schedule_guard_update() RETURNS trigger AS $$
BEGIN
  IF OLD."status" <> 'Scheduled' THEN
    RAISE EXCEPTION 'A completed or superseded review schedule is history and cannot be changed';
  END IF;
  IF NEW."customer_id" IS DISTINCT FROM OLD."customer_id" THEN
    RAISE EXCEPTION 'A review schedule cannot be moved to another customer';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "ReviewSchedule_guard" BEFORE UPDATE ON "ReviewSchedule" FOR EACH ROW EXECUTE FUNCTION review_schedule_guard_update();
