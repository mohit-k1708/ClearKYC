-- ===========================================================================
-- 5. Triggers
-- ===========================================================================
-- AUDIT EVENTS ARE IMMUTABLE. Updates are always refused. Deletes and truncates are refused unless the explicit
-- maintenance switch (SET LOCAL app.allow_history_delete = 'on') is set, which only the synthetic-data reset scripts
-- and the test-suite cleanup use. No application endpoint sets it.
CREATE FUNCTION audit_event_block_update() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'Audit events are immutable and cannot be updated';
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION audit_event_block_delete() RETURNS trigger AS $$
BEGIN
  IF coalesce(current_setting('app.allow_history_delete', true), '') <> 'on' THEN
    RAISE EXCEPTION 'Audit events are immutable and cannot be deleted';
  END IF;
  RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE FUNCTION audit_event_block_truncate() RETURNS trigger AS $$
BEGIN
  IF coalesce(current_setting('app.allow_history_delete', true), '') <> 'on' THEN
    RAISE EXCEPTION 'Audit events are immutable and cannot be truncated';
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "AuditEvent_no_update" BEFORE UPDATE ON "AuditEvent" FOR EACH ROW EXECUTE FUNCTION audit_event_block_update();
CREATE TRIGGER "AuditEvent_no_delete" BEFORE DELETE ON "AuditEvent" FOR EACH ROW EXECUTE FUNCTION audit_event_block_delete();
CREATE TRIGGER "AuditEvent_no_truncate" BEFORE TRUNCATE ON "AuditEvent" FOR EACH STATEMENT EXECUTE FUNCTION audit_event_block_truncate();

-- Alerts are never deleted directly (only the cascade from deleting a whole customer, or the maintenance switch).
CREATE TRIGGER "Alert_no_delete" BEFORE DELETE ON "Alert" FOR EACH ROW EXECUTE FUNCTION history_block_delete();

-- A RESOLVED or DISMISSED alert is a historical record. Only the housekeeping flag suppress_regeneration
-- (and updated_at) may change. If the condition returns, detection raises a NEW alert.
CREATE FUNCTION alert_guard_update() RETURNS trigger AS $$
BEGIN
  IF NEW."customer_id" IS DISTINCT FROM OLD."customer_id"
     OR NEW."alert_type" IS DISTINCT FROM OLD."alert_type"
     OR NEW."dedupe_key" IS DISTINCT FROM OLD."dedupe_key"
     OR NEW."alert_code" IS DISTINCT FROM OLD."alert_code"
     OR NEW."created_at" IS DISTINCT FROM OLD."created_at" THEN
    RAISE EXCEPTION 'An alert identity (customer, type, condition, code, creation date) cannot be changed';
  END IF;
  IF OLD."status" IN ('Resolved', 'Dismissed') THEN
    IF NEW."status" IS DISTINCT FROM OLD."status"
       OR NEW."resolved_at" IS DISTINCT FROM OLD."resolved_at"
       OR NEW."resolved_by_id" IS DISTINCT FROM OLD."resolved_by_id"
       OR NEW."resolution_type" IS DISTINCT FROM OLD."resolution_type"
       OR NEW."resolution_notes" IS DISTINCT FROM OLD."resolution_notes"
       OR NEW."severity" IS DISTINCT FROM OLD."severity"
       OR NEW."description" IS DISTINCT FROM OLD."description"
       OR NEW."acknowledged_at" IS DISTINCT FROM OLD."acknowledged_at"
       OR NEW."acknowledged_by_id" IS DISTINCT FROM OLD."acknowledged_by_id" THEN
      RAISE EXCEPTION 'A resolved or dismissed alert is a historical record and cannot be changed. A returning condition creates a new alert';
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "Alert_guard" BEFORE UPDATE ON "Alert" FOR EACH ROW EXECUTE FUNCTION alert_guard_update();

