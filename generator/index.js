#!/usr/bin/env node
/**
 * ClearKYC synthetic data generator (Phase 2).
 *
 *   npm run generate:starter | generate:medium | generate:full
 *   node generator/index.js --scale=full --seed=20261022 --reference-date=2026-10-31 --batch-size=1000 [--reset] [--skip-validation]
 *
 * What it does
 *   1. resolves the central configuration (generator/config/generatorConfig.js + command line);
 *   2. creates / migrates its OWN database (clearkyc_<scale>) and refuses to touch a database that already holds data
 *      unless --reset is given (the main "clearkyc" database additionally needs --confirm-reset-main-database);
 *   3. builds every entity in memory, parents first, with deterministic IDs and the application's own business rules;
 *   4. writes everything with batched createMany, in dependency order, timing each stage;
 *   5. makes the application continue the ID series (sequences + counters), validates the result and writes the reports.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { performance } = require('perf_hooks');
const { resolveConfig } = require('./config/generatorConfig');
const { prepareDatabase } = require('./utils/database');
const { Metrics, insertBatches, syncSerial, setSequence } = require('./utils/batchInsert');
const { createRng } = require('./utils/seededRandom');
const { ScopedCounter } = require('./utils/idGenerator');

const omit = (rows, keys) => rows.map((row) => {
  const copy = { ...row };
  for (const k of keys) delete copy[k];
  return copy;
});
const fmt = (n) => Number(n).toLocaleString('en-US');
const seconds = (ms) => (ms / 1000).toFixed(2);

const CHECKSUM_TABLES = [
  ['Reviewer', 'id'], ['KYCRequirement', 'id'], ['Customer', 'id'], ['BeneficialOwner', 'id'], ['OwnerScreening', 'id'], ['OwnershipValidation', 'id'], ['Document', 'id'], ['Verification', 'id'],
  ['RiskRating', 'id'], ['OnboardingDecision', 'id'], ['ReviewSchedule', 'id'], ['Exception', 'id'], ['ReviewCase', 'id'], ['CaseHistory', 'id'], ['CaseNote', 'id'], ['Alert', 'id'], ['AuditEvent', 'id'],
];

async function checksums(prisma) {
  const out = {};
  for (const [table, key] of CHECKSUM_TABLES) {
    const [{ sum, n }] = await prisma.$queryRawUnsafe(`SELECT md5(coalesce(string_agg(md5(t::text), '' ORDER BY t."${key}"), '')) AS sum, count(*)::int AS n FROM "${table}" t`);
    out[table] = { rows: n, checksum: sum };
  }
  // generated by a database trigger (timestamps are the time of insertion), so only the business columns are compared
  const [own] = await prisma.$queryRawUnsafe(`SELECT md5(coalesce(string_agg(md5(row(company_customer_id, beneficial_owner_id, person_ref, ownership_percentage, ownership_type, control_type, effective_from, effective_to)::text), '' ORDER BY company_customer_id, beneficial_owner_id, id), '')) AS sum, count(*)::int AS n FROM "CompanyOwnership"`);
  out.CompanyOwnership = { rows: own.n, checksum: own.sum };
  const [ids] = await prisma.$queryRawUnsafe(`SELECT md5(coalesce(string_agg(md5(t::text), '' ORDER BY scope, period), '')) AS sum, count(*)::int AS n FROM "IdCounter" t`);
  out.IdCounter = { rows: ids.n, checksum: ids.sum };
  out.dataset = crypto.createHash('md5').update(Object.keys(out).sort().map((k) => `${k}:${out[k].checksum}`).join('|')).digest('hex');
  return out;
}

async function generate(argv = process.argv.slice(2)) {
  const cfg = resolveConfig(argv);
  const metrics = new Metrics();
  const { prisma, createdDatabase } = await prepareDatabase(cfg); // sets DATABASE_URL: the application modules are loaded after this

  const { generateReference } = require('./generators/referenceGenerator');
  const { generateCustomers } = require('./generators/customerGenerator');
  const { generateOwnership } = require('./generators/ownershipGenerator');
  const { generateRisk } = require('./generators/riskGenerator');
  const { generateDocuments } = require('./generators/documentGenerator');
  const { generateApprovals } = require('./generators/approvalGenerator');
  const { generateReview } = require('./generators/reviewGenerator');
  const { generateAlerts } = require('./generators/alertGenerator');
  const { generateAudit } = require('./generators/auditGenerator');
  const { runValidation } = require('./validation/postGenerationValidation');

  const rng = createRng(cfg.seed);
  const counters = new ScopedCounter();
  const timed = (entity, count, fn) => {
    const t0 = performance.now();
    const result = fn();
    metrics.record(entity, typeof count === 'function' ? count(result) : count, performance.now() - t0, 'generate');
    return result;
  };

  let validation = null;
  let sums = null;
  let failure = null;
  const info = {};
  try {
    // ---- 1. build everything in memory (parents before the records that depend on them) -------------------------------
    const reference = timed('Reference data', (x) => x.requirements.length + x.people.all.length + 2, () => generateReference(cfg, counters));
    const customers = timed('Customers', (x) => x.length, () => generateCustomers(cfg, rng));
    const ownership = timed('BeneficialOwners', (x) => x.owners.length, () => generateOwnership(cfg, rng, customers, reference.people));
    const risk = timed('RiskRatings', (x) => x.ratings.length, () => generateRisk(cfg, rng, customers, ownership.ownersByCompany, reference.people));
    const documents = timed('Documents + Verifications', (x) => x.documents.length + x.verifications.length, () => generateDocuments(cfg, rng, customers, risk.currentByCustomer, reference.requirements, reference.people, counters));
    const approvals = timed('OnboardingDecisions', (x) => x.decisions.length, () => generateApprovals(cfg, rng, customers, risk.ratings, documents.documents, reference.requirements, reference.people));
    const review = timed('Schedules + Exceptions + Cases', (x) => x.schedules.length + x.exceptions.length + x.cases.length, () => generateReview(cfg, rng, {
      customers, currentRisk: risk.currentByCustomer, ownersByCompany: ownership.ownersByCompany, ownership, documents: documents.documents, requirements: reference.requirements,
      validations: ownership.validations, people: reference.people, counters,
    }));
    const alertResult = timed('Alerts', (x) => x.alerts.length, () => generateAlerts(cfg, rng, {
      contexts: review.contexts, conditionsByCustomer: review.conditionsByCustomer, activeByKey: review.activeByKey, exceptions: review.exceptions, documents: documents.documents, customers, people: reference.people, counters,
    }));
    const audit = timed('AuditEvents', (x) => x.events.length, () => generateAudit(cfg, rng, {
      customers, reference, ownership, risk, documents, review, approvals, alerts: alertResult.alerts, cases: review.cases,
    }));
    Object.assign(info, { approvals: approvals.stats, ownership: ownership.summary, documents: documents.summary, review: review.stats, alerts: alertResult.stats, audit: { events: audit.stats.events } });

    // ---- 2. write, in dependency order ---------------------------------------------------------------------------------
    const bs = cfg.batchSize;
    const ins = (entity, model, rows) => insertBatches(prisma, metrics, entity, model, rows, bs);
    metrics.record('CustomerType', reference.customerTypes.length, 0, 'existing'); // created by the first migration
    await ins('Reviewer', 'reviewer', reference.people.all);
    await ins('KYCRequirement', 'kYCRequirement', omit(reference.requirements, ['customerType']));
    await ins('Customer', 'customer', customers.map((c) => c.row));
    await ins('BeneficialOwner', 'beneficialOwner', ownership.owners); // the database trigger fills CompanyOwnership as these are inserted
    metrics.record('CompanyOwnership', await prisma.companyOwnership.count(), 0, 'trigger');
    await ins('OwnerScreening', 'ownerScreening', ownership.screenings);
    await ins('OwnershipValidation', 'ownershipValidation', ownership.validations);
    await ins('Document', 'document', documents.documents.map((d) => d.row));
    // The "newest verification sets Document.status" trigger would overwrite updated_at with the clock time; the final status is
    // already stored on each document, and the validation below proves it equals the newest verification.
    await prisma.$executeRawUnsafe('ALTER TABLE "Verification" DISABLE TRIGGER "Verification_sync_status"');
    try {
      await ins('Verification', 'verification', omit(documents.verifications, ['seq']));
    } finally {
      await prisma.$executeRawUnsafe('ALTER TABLE "Verification" ENABLE TRIGGER "Verification_sync_status"');
    }
    await ins('RiskRating', 'riskRating', risk.ratings);
    await ins('OnboardingDecision', 'onboardingDecision', approvals.decisions);
    await ins('ReviewSchedule', 'reviewSchedule', omit(review.schedules, ['lastIso', 'nextIso', 'completionIso', 'lateDays']));
    await ins('Exception', 'exception', omit(review.exceptions, ['cases', 'historical', 'kind', 'schedule'])); // before the cases, which reference them
    await ins('ReviewCase', 'reviewCase', omit(review.cases, ['steps', 'customerCode', 'pendingNotes']));
    await ins('CaseHistory', 'caseHistory', review.caseHistory);
    await ins('CaseNote', 'caseNote', review.caseNotes);
    await ins('Alert', 'alert', omit(alertResult.alerts, ['historical']));
    await ins('AuditEvent', 'auditEvent', audit.events);

    // ---- 3. let the application carry on after the generated data -----------------------------------------------------
    await metrics.time('ID sequences + counters', 'finalize', 1, async () => {
      for (const table of ['Reviewer', 'KYCRequirement', 'Customer', 'BeneficialOwner', 'OwnerScreening', 'OwnershipValidation', 'Document', 'Verification', 'RiskRating', 'OnboardingDecision', 'ReviewSchedule', 'Exception', 'ReviewCase', 'CaseHistory', 'CaseNote', 'Alert', 'AuditEvent']) {
        await syncSerial(prisma, table);
      }
      await setSequence(prisma, 'customer_code_seq', customers.length);
      await setSequence(prisma, 'risk_assessment_seq', risk.ratings.length);
      await setSequence(prisma, 'exception_seq', review.exceptions.length);
      await setSequence(prisma, 'review_case_seq', review.cases.length);
      await setSequence(prisma, 'alert_seq', alertResult.alerts.length);
      await setSequence(prisma, 'audit_event_seq', audit.events.length);
      await prisma.idCounter.createMany({ data: counters.rows() });
    });

    // ---- 4. validate + checksums ---------------------------------------------------------------------------------------------
    if (!cfg.skipValidation) validation = await metrics.time('Post-generation validation', 'validate', 1, () => runValidation(prisma, cfg));
    sums = await metrics.time('Checksums', 'validate', 1, () => checksums(prisma));
  } catch (err) {
    failure = err;
    metrics.error('generator', err.stack || err.message);
  }

  const summary = buildSummary(cfg, metrics, validation, sums, info, failure, createdDatabase);
  await prisma.$disconnect();
  // the application's own client (used by the validation) must not keep this database busy: other tools copy it afterwards
  try { await require('../server/src/utils/prisma').$disconnect(); } catch { /* it was never loaded */ }
  writeReports(cfg, summary);
  return summary;
}

function buildSummary(cfg, metrics, validation, sums, info, failure, createdDatabase) {
  const byEntity = new Map();
  for (const s of metrics.stages) {
    if (!byEntity.has(s.entity)) byEntity.set(s.entity, { entity: s.entity, records: 0, generateMs: 0, insertMs: 0, otherMs: 0 });
    const e = byEntity.get(s.entity);
    e.records = Math.max(e.records, s.records);
    if (s.kind === 'generate') e.generateMs += s.ms;
    else if (s.kind === 'insert') e.insertMs += s.ms;
    else e.otherMs += s.ms;
  }
  const stages = [...byEntity.values()].map((e) => {
    const totalMs = e.generateMs + e.insertMs + e.otherMs;
    return { ...e, totalMs, recordsPerSecond: totalMs > 0 ? Math.round((e.records / totalMs) * 1000) : null };
  });
  const failedRecords = failure ? cfg.counts.customers : 0;
  return {
    status: failure ? 'FAILED' : validation && validation.status !== 'PASSED' ? 'COMPLETED WITH VALIDATION FAILURES' : 'SUCCESS',
    seed: cfg.seed, scale: cfg.scale, referenceDate: cfg.referenceDate, batchSize: cfg.batchSize, database: cfg.databaseName, databaseCreated: createdDatabase,
    counts: cfg.counts, totalMs: metrics.totalMs(), stages, errors: metrics.errors, failedRecords: failure ? 'unknown (run aborted)' : 0, details: info,
    validation, checksums: sums, failedRecordCount: failedRecords,
    memory: { peak_rss_mb: Math.round(process.resourceUsage().maxRSS / 1024), heap_used_mb: Math.round(process.memoryUsage().heapUsed / 1048576) }, // observed by this run (machine-dependent)
    generatedAtWallClock: new Date().toISOString(), // the only wall-clock value; it is not part of the data
  };
}

function printSummary(s) {
  const line = (label, value) => console.log(`  ${label.padEnd(26, '.')} ${value}`);
  console.log('\n==================== ClearKYC data generation ====================');
  line('Status', s.status);
  line('Seed', s.seed);
  line('Scale', s.scale);
  line('Reference date', s.referenceDate);
  line('Database', `${s.database}${s.databaseCreated ? ' (created)' : ''}`);
  line('Batch size', s.batchSize);
  line('Customers', `${fmt(s.counts.customers)} (${fmt(s.counts.individuals)} individuals, ${fmt(s.counts.companies)} companies)`);
  if (s.details.documents) {
    line('Documents', `${fmt(s.details.documents.documents)} (${fmt(s.details.documents.replacements)} replacements)`);
    line('Review cases', fmt(s.details.review.cases));
    line('Owners / alerts / audit', `${fmt(s.details.ownership.ownerRows)} / ${fmt(s.details.alerts.alerts)} / ${fmt(s.details.audit.events)}`);
  }
  line('Total time', `${seconds(s.totalMs)} s`);
  if (s.memory) line('Peak memory', `${s.memory.peak_rss_mb} MB resident (heap in use at the end: ${s.memory.heap_used_mb} MB)`);
  line('Failed records', s.failedRecords);
  line('Validation', s.validation ? `${s.validation.status} (${s.validation.passed}/${s.validation.checks} checks passed; application checks failed: ${s.validation.applicationFailed ?? 'n/a'})` : 'skipped');
  console.log('\n  Stage                              Records   Generate s   Insert s    Total s   Records/s');
  for (const e of s.stages) {
    console.log(`  ${e.entity.padEnd(32)} ${fmt(e.records).padStart(9)} ${seconds(e.generateMs).padStart(12)} ${seconds(e.insertMs).padStart(10)} ${seconds(e.totalMs).padStart(10)} ${e.recordsPerSecond === null ? '-'.padStart(11) : fmt(e.recordsPerSecond).padStart(11)}`);
  }
  if (s.errors.length) {
    console.log('\n  ERRORS');
    for (const e of s.errors) console.log(`  - ${e.entity}: ${e.message}`);
  }
  if (s.validation) {
    for (const f of s.validation.results.filter((x) => !x.passed)) console.log(`  FAILED CHECK [${f.group}] ${f.name}: ${f.detail} ${f.examples.length ? JSON.stringify(f.examples) : ''}`);
    for (const f of (s.validation.application || []).filter((x) => x.outcome !== 'Passed')) console.log(`  APP CHECK ${f.outcome}: ${f.code} ${f.title} (${f.issues} issue(s))`);
  }
  if (s.checksums) line('Dataset checksum', s.checksums.dataset);
  console.log('==================================================================\n');
}

function writeReports(cfg, s) {
  const dir = cfg.reportDir ? path.resolve(cfg.reportDir) : path.join(__dirname, 'reports', cfg.scale);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'generation_summary.json'), JSON.stringify(s, null, 2));
  const perf = [
    `# Performance report - scale ${s.scale}`, '', `Seed ${s.seed}, reference date ${s.referenceDate}, batch size ${s.batchSize}, database ${s.database}. Total ${seconds(s.totalMs)} s.`, '',
    '| Entity | Records | Generate (s) | Insert (s) | Total (s) | Records/sec | Errors |', '|---|---:|---:|---:|---:|---:|---:|',
    ...s.stages.map((e) => `| ${e.entity} | ${fmt(e.records)} | ${seconds(e.generateMs)} | ${seconds(e.insertMs)} | ${seconds(e.totalMs)} | ${e.recordsPerSecond === null ? '-' : fmt(e.recordsPerSecond)} | ${s.errors.filter((x) => x.entity === e.entity).length} |`),
    '', `Failed records: ${s.failedRecords}`,
  ];
  fs.writeFileSync(path.join(dir, 'performance_report.md'), perf.join('\n'));
  if (s.validation) {
    const v = s.validation;
    const rows = [
      `# Validation report - scale ${s.scale}`, '', `**${v.status}** - ${v.passed}/${v.checks} database checks passed. Application data-quality checks: ${(v.application || []).length} run, ${v.applicationFailed} failed, ${v.applicationWarnings} with warnings.`, '',
      '| Group | Check | Result | Detail |', '|---|---|---|---|',
      ...v.results.map((x) => `| ${x.group} | ${x.name.replace(/\|/g, '/')} | ${x.passed ? 'PASS' : 'FAIL'} | ${x.detail} |`),
      '', '## Application data-quality checks', '', '| Code | Check | Outcome | Issues |', '|---|---|---|---:|',
      ...(v.application || []).map((x) => `| ${x.code} | ${x.title} | ${x.outcome} | ${x.issues ?? '-'} |`),
    ];
    fs.writeFileSync(path.join(dir, 'validation_report.md'), rows.join('\n'));
  }
  if (s.checksums) fs.writeFileSync(path.join(dir, 'checksums.json'), JSON.stringify(s.checksums, null, 2));
}

if (require.main === module) {
  generate()
    .then((summary) => {
      printSummary(summary);
      process.exit(summary.status === 'SUCCESS' ? 0 : 1);
    })
    .catch((err) => {
      console.error(`\nGeneration stopped: ${err.message}\n`);
      process.exit(1);
    });
}

module.exports = { generate, printSummary };
